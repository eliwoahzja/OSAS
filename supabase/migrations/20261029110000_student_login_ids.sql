-- Student IDs replace usernames for login. Preserve legacy usernames/data;
-- never change Auth UUIDs, passwords, emails, or existing record ownership.
ALTER TABLE public.users ADD COLUMN student_id text;
CREATE SEQUENCE public.osas_student_id_sequence AS bigint MAXVALUE 9999999 NO CYCLE;
REVOKE ALL ON SEQUENCE public.osas_student_id_sequence FROM PUBLIC, anon, authenticated;

CREATE FUNCTION public.osas_assign_student_id()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  saved_id text;
  number bigint;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.student_id IS DISTINCT FROM OLD.student_id THEN
      RAISE EXCEPTION 'Student IDs are generated automatically and cannot be edited.' USING ERRCODE = '23514';
    END IF;
    saved_id := OLD.student_id;
  ELSE
    SELECT student_id INTO saved_id FROM public.users WHERE id = NEW.id;
    IF NEW.student_id IS NOT NULL AND NEW.student_id IS DISTINCT FROM saved_id THEN
      RAISE EXCEPTION 'Student IDs are generated automatically and cannot be supplied.' USING ERRCODE = '23514';
    END IF;
  END IF;
  NEW.student_id := saved_id;
  IF NEW.student_id IS NULL AND EXISTS (
    SELECT 1 FROM auth.users WHERE id = NEW.id AND raw_app_meta_data->>'role' = 'client'
  ) THEN
    number := nextval('public.osas_student_id_sequence');
    NEW.student_id := 's' || to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila', 'YY')
      || lpad(number::text, 7, '0');
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.osas_assign_student_id() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER osas_assign_student_id
  BEFORE INSERT OR UPDATE ON public.users
  FOR EACH ROW EXECUTE FUNCTION public.osas_assign_student_id();

-- Deterministic backfill. The year is the year of ID issuance, not enrollment.
DO $$
DECLARE account record;
BEGIN
  FOR account IN SELECT u.id FROM public.users u JOIN auth.users a USING (id)
    WHERE a.raw_app_meta_data->>'role' = 'client' ORDER BY a.created_at, a.id
  LOOP
    UPDATE public.users SET student_id = student_id WHERE id = account.id;
  END LOOP;
END;
$$;
ALTER TABLE public.users ADD CONSTRAINT users_student_id_key UNIQUE (student_id);
ALTER TABLE public.users ADD CONSTRAINT users_student_id_format
  CHECK (student_id IS NULL OR student_id ~ '^s[0-9]{9}$');

-- Profile sync also handles Supabase Auth's insert-then-metadata update flow.
-- IDs are generated by the profile trigger, never from editable metadata.
CREATE OR REPLACE FUNCTION public.osas_sync_account_profile()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  INSERT INTO public.users (id, email, full_name, role, created_at)
  VALUES (NEW.id, NEW.email,
    COALESCE(NULLIF(NEW.raw_user_meta_data->>'name', ''), NEW.email, 'Account'),
    CASE WHEN NEW.raw_app_meta_data->>'role' = 'admin' THEN 'admin' ELSE 'staff' END,
    NEW.created_at)
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email, full_name = EXCLUDED.full_name, role = EXCLUDED.role;
  RETURN NEW;
END;
$$;

COMMENT ON COLUMN public.users.student_id IS
  'Auto-generated, immutable student login ID. Not an official enrollment number. Resolves to the saved Auth email; never grants access without password/OTP.';
